"""Shared helpers for Company Brain harness CLIs.

The harness intentionally avoids non-stdlib dependencies. Config parsing is a
small YAML subset tailored to the deployment config shape generated by this
package.
"""
from __future__ import annotations

import os
from pathlib import Path


DEFAULT_CONVENTIONS_DIR = "system"
LEGACY_CONVENTIONS_DIRS = ("system", "system")
DEFAULT_STAGING_DIR = f"{DEFAULT_CONVENTIONS_DIR}/staging"
DEFAULT_ROUTING_FILE = "CLAUDE.md"
DEFAULT_RESTRICTED_PREFIXES = ("brain/restricted", "restricted", "Restricted", "14_Owner_Vault")

CONFIG_CANDIDATES = (
    "company-brain.yml",
    "company-os.yml",
    f"{DEFAULT_CONVENTIONS_DIR}/company-brain.yml",
    f"{DEFAULT_CONVENTIONS_DIR}/company-os.yml",
    "system/company-brain.yml",
    "system/company-os.yml",
    "system/company-brain.yml",
    "system/company-os.yml",
)


def resolve_root(value: str | None = None) -> Path:
    root = (
        value
        or os.environ.get("BRAIN_ROOT")
        or os.environ.get("COMPANY_BRAIN_ROOT")
        or os.environ.get("COMPANY_OS_ROOT")
        or os.getcwd()
    )
    return Path(root).expanduser().resolve()


def find_config_path(root: Path) -> Path | None:
    for rel in CONFIG_CANDIDATES:
        path = root / rel
        if path.is_file():
            return path
    return None


def _strip_comment(line: str) -> str:
    in_quote: str | None = None
    out = []
    for ch in line:
        if ch in {"'", '"'}:
            in_quote = None if in_quote == ch else ch
        if ch == "#" and in_quote is None:
            break
        out.append(ch)
    return "".join(out).rstrip()


def _unquote(value: str) -> str:
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in {"'", '"'}:
        return value[1:-1]
    return value


def _section_lines(root: Path, section: str) -> list[str]:
    path = find_config_path(root)
    if path is None:
        return []
    lines = path.read_text(encoding="utf-8", errors="ignore").splitlines()
    start = None
    for i, raw in enumerate(lines):
        if raw.startswith(f"{section}:"):
            start = i + 1
            break
    if start is None:
        return []

    out = []
    for raw in lines[start:]:
        if raw and not raw.startswith((" ", "\t")):
            break
        out.append(raw)
    return out


def config_scalar(root: Path, section: str, key: str, default: str) -> str:
    for raw in _section_lines(root, section):
        line = _strip_comment(raw)
        if not line.strip() or ":" not in line:
            continue
        stripped = line.strip()
        if not stripped.startswith(f"{key}:"):
            continue
        value = stripped.split(":", 1)[1].strip()
        if value:
            return _unquote(value)
    return default


def config_list(root: Path, section: str, key: str, default: tuple[str, ...]) -> list[str]:
    lines = _section_lines(root, section)
    for i, raw in enumerate(lines):
        line = _strip_comment(raw)
        if line.strip() != f"{key}:":
            continue
        items: list[str] = []
        for item_raw in lines[i + 1:]:
            item_line = _strip_comment(item_raw)
            stripped = item_line.strip()
            if not stripped:
                continue
            if not stripped.startswith("- "):
                break
            value = _unquote(stripped[2:].strip())
            if value:
                items.append(value)
        return items or list(default)
    return list(default)


def _env_csv(name: str) -> list[str]:
    value = os.environ.get(name, "")
    return [part.strip() for part in value.split(",") if part.strip()]


def routing_file(root: Path) -> Path:
    rel = os.environ.get("BRAIN_ROUTING_FILE") or config_scalar(
        root, "brain", "routing_file", DEFAULT_ROUTING_FILE
    )
    return root / safe_relative_path(rel, name="routing file")


def conventions_dir(root: Path) -> Path:
    default = DEFAULT_CONVENTIONS_DIR
    if not (root / DEFAULT_CONVENTIONS_DIR).exists():
        for legacy in LEGACY_CONVENTIONS_DIRS:
            if (root / legacy).exists():
                default = legacy
                break
    rel = os.environ.get("BRAIN_CONVENTIONS_DIR") or config_scalar(
        root, "brain", "conventions_dir", default
    )
    return root / safe_relative_path(rel, name="conventions dir")


def staging_dir(root: Path, override: str | None = None) -> Path:
    conv = conventions_dir(root).relative_to(root).as_posix()
    default_staging = f"{conv}/staging"
    if (root / conv / "system/staging").exists() and not (root / conv / "staging").exists():
        default_staging = f"{conv}/system/staging"
    rel = (
        override
        or os.environ.get("BRAIN_STAGING_DIR")
        or config_scalar(root, "brain", "staging_dir", default_staging)
    )
    return root / safe_relative_path(rel, name="staging dir")


def restricted_prefixes(root: Path, extras: list[str] | None = None) -> list[str]:
    prefixes = _env_csv("BRAIN_RESTRICTED_PREFIXES") or config_list(
        root, "brain", "restricted_prefixes", DEFAULT_RESTRICTED_PREFIXES
    )
    for prefix in extras or []:
        if prefix not in prefixes:
            prefixes.append(prefix)
    return prefixes


def safe_relative_path(value: str | Path, *, name: str) -> Path:
    rel = Path(value)
    if rel.is_absolute():
        raise ValueError(f"{name} must be relative to the brain root")
    if any(part in {"", ".", ".."} for part in rel.parts):
        raise ValueError(f"{name} must not contain empty, '.', or '..' path parts")
    return rel


def path_has_prefix(rel: Path, prefix: str | Path) -> bool:
    prefix_path = Path(prefix)
    if prefix_path.is_absolute() or any(part in {"", ".", ".."} for part in prefix_path.parts):
        return False
    if len(rel.parts) < len(prefix_path.parts):
        return False
    return rel.parts[: len(prefix_path.parts)] == prefix_path.parts
